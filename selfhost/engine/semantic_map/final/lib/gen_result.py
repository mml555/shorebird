#!/usr/bin/env python3
"""Generate RESULT.md from the matrix, the verdict and the manifest.

#58 requires a RESULT.md; the authorization requires it be GENERATED from the
same machine-readable artifacts rather than independently authored, with
numerical prose derived from current structured evidence.

So there is no hand-written number anywhere below. Every figure is read out of
final_matrix.json / final_verdict.json / provenance_manifest.json at write
time. This matters concretely: a commit message in this programme once carried
G7 figures from a PRIOR run because the gate had no generated report to read
from, and the two copies drifted silently.

usage: gen_result.py <matrix.json> <verdict.json> <manifest.json> <out.md>
"""
import json
import sys

matrix_doc = json.load(open(sys.argv[1]))
verdict_doc = json.load(open(sys.argv[2]))
manifest = json.load(open(sys.argv[3]))
OUT = sys.argv[4]

M = matrix_doc['matrix']
V = verdict_doc
out = []
def w(s=''): out.append(s)


def pv(row, name, default='n/a'):
    return M.get(row, {}).get('probe_values', {}).get(name, default)


w('# SEMANTIC-MAP-1 — FINAL')
w()
w('<!-- GENERATED by final/lib/gen_result.py. Do not edit: every number here')
w('     is read from evidence/final_matrix.json, evidence/final_verdict.json')
w('     and evidence/provenance_manifest.json at write time. Editing this')
w('     file creates a second copy of the numbers, free to drift from the')
w('     evidence -- which already happened in this programme once. -->')
w()
w(f'Generated {matrix_doc["generated"]} · issue #{matrix_doc["issue"]} · '
  f'tracker #{matrix_doc["tracker"]}')
w()

# INCOMPLETENESS LEADS. When a row could not be resolved the assembler
# degrades correctly -- it reports NOT_ESTABLISHED -- but no STAGE exits
# non-zero, so without this banner the report reads like a complete one and a
# reader could take the verdict at face value. The stale-output control caught
# exactly that: corrupted evidence produced a normal-looking RESULT.md.
incomplete = V['rows_not_established']
if incomplete:
    w('> ## ⚠ THIS ASSEMBLY IS INCOMPLETE')
    w('>')
    w(f'> {len(incomplete)} matrix row(s) could not be resolved from evidence '
      f'and read `NOT_ESTABLISHED`:')
    w('>')
    for r in incomplete:
        w(f'> - `{r}` — {M[r]["note"]}')
    w('>')
    w('> The verdict below was computed over a matrix with those rows missing. '
      'It is **provisional** and must not be cited as this lane\'s result '
      'until the evidence pointers resolve.')
    w()
w('## Verdict')
w()
w(f'    {V["verdict"]}'
  + ('   (PROVISIONAL -- incomplete matrix)' if incomplete else ''))
w()
w(f'Selected by the predicate `{V["selected_by_predicate"]}`, applying '
  f"#58's precedence.")
w()
w('The verdict is **computed from the matrix**, not declared beside it. Every '
  'predicate is published below, not only the one that selected, so the '
  'decision surface is visible and the outcome can be checked for having been '
  'reachable any other way.')
w()
w('| verdict | predicate | value | selected |')
w('| --- | --- | --- | --- |')
for t in V['ladder_trace']:
    w(f'| `{t["verdict"]}` | `{t["predicate"]}` | {t["value"]} | '
      f'{"**yes**" if t["selected"] else "no"} |')
w()
w('## The matrix')
w()
w('Every row is extracted at run time from a named file and field or marker. '
  'A row whose evidence cannot be resolved reads `NOT_ESTABLISHED` and is '
  'never filled from a remembered conclusion.')
w()
w('| row | category | evidence |')
w('| --- | --- | --- |')
for name, r in M.items():
    files = ', '.join(f'`{f}`' for f in r.get('evidence_files', [])) or '—'
    w(f'| `{name}` | `{r["category"]}` | {files} |')
if V['rows_not_established']:
    w()
    w(f'**NOT_ESTABLISHED rows:** '
      f'{", ".join("`" + r + "`" for r in V["rows_not_established"])}')
else:
    w()
    w('No row is `NOT_ESTABLISHED`: every declared evidence pointer resolved.')
w()
w('### What each non-positive category means here')
w()
for name, r in M.items():
    if r['category'] in ('VACUOUS', 'ESTABLISHED_NEGATIVE',
                         'ESTABLISHED_WITH_LIMITS', 'NOT_ESTABLISHED',
                         'MEASURED_CURRENT_RUN_ONLY',
                         'MEASURED_DETERMINISTIC_PROJECTION_LOW'):
        w(f'**`{name}` — `{r["category"]}`**  ')
        w(f'{r["note"]}')
        w()
w('## Measurements')
w()
w('Deterministic and timing families are kept separate. The deterministic '
  'figures are artifact-derived and identical across runs; the timing figures '
  'are current-run observations and are not reproducible.')
w()
w('| figure | value | family |')
w('| --- | --- | --- |')
w(f'| declarations in cost scope | {pv("MAP_SIZE", "declarations"):,} | '
  f'deterministic |')
w(f'| map bytes | {pv("MAP_SIZE", "map_bytes"):,} | deterministic |')
w(f'| release AOT bytes | {pv("MAP_SIZE", "aot_bytes"):,} | deterministic |')
w(f'| map / AOT | {pv("MAP_SIZE", "pct")} % | deterministic |')
w(f'| retention cost measured | '
  f'{pv("RETENTION_COST_AT_SCALE", "measured_delta"):,} bytes '
  f'({pv("RETENTION_COST_AT_SCALE", "measured_pct")} %) | deterministic |')
w(f'| G4 projection | '
  f'{pv("RETENTION_COST_AT_SCALE", "projection"):,} bytes | deterministic |')
w(f'| measured / projected | '
  f'{pv("RETENTION_COST_AT_SCALE", "ratio")} × | deterministic |')
w(f'| timed stages | {pv("GENERATION_TIME", "stages")} | '
  f'**current run only** |')
w(f'| timing samples | {pv("GENERATION_TIME", "samples")} '
  f'({pv("GENERATION_TIME", "failed_samples")} failed) | '
  f'**current run only** |')
w(f'| order-dependent labels | {pv("GENERATION_TIME", "order_dependent")} | '
  f'**current run only** |')
w()
w('## Known gaps')
w()
gaps = M['KNOWN_GAPS']
w(f'{gaps["count"]} entries, generated from the matrix categories, the G8 '
  f'production prerequisites and the G8 reproduced FAIL_OPEN findings. '
  f'`UNKNOWN`, `VACUOUS`, `NOT_ESTABLISHED` and unresolved prerequisites '
  f'appear verbatim.')
w()
w('| source | id | category | detail |')
w('| --- | --- | --- | --- |')
for g in gaps['entries']:
    detail = (g.get('detail') or '').replace('|', '\\|')
    w(f'| {g["source"]} | `{g["id"]}` | `{g["category"]}` | {detail} |')
w()
w('## Non-proven claims, stated exactly')
w()
for c in V['non_proven_claims']:
    w(f'- {c}')
w()
w('## Next lane')
w()
for r in V['next_lane']:
    w(f'- {r}')
w()
w('## Provenance')
w()
w(f'{manifest["consumed_count"]} evidence files consumed, each digested at '
  f'read time; {len(manifest["producing_scripts"])} producing scripts and '
  f'{len(manifest["assembler"])} assembler components digested.')
w()
w(f'Input set derived from {manifest["input_set_derived_from"]}. '
  f'Declared by rows: {manifest["coverage"]["declared_by_rows"]}; opened by '
  f'the extractor: {manifest["coverage"]["opened_by_extractor"]}; sets equal: '
  f'{manifest["coverage"]["equal"]}.')
w()
w(f'Self-hashing: {manifest["self_hashing"]}')
w()
w(f'Manifest findings: '
  f'{manifest["findings"] if manifest["findings"] else "none"}.')
w()
w('| evidence | sha256 | rows |')
w('| --- | --- | --- |')
for rel, rec in manifest['consumed_evidence'].items():
    w(f'| `{rel}` | `{rec["sha256"][:16]}…` | {len(rec["rows"])} |')
w()
w('## Scope boundary')
w()
w('This lane extracted and classified. It implemented nothing: no patch-v2 '
  'format, no CLI integration, no signing change, no supported-state change, '
  'no physical deployment, and no `AOT-ASSUMPTIONS-1` work. No Mutable-AOT '
  'implementation began here.')

open(OUT, 'w').write('\n'.join(out) + '\n')
print(f'  RESULT.md generated: {len(out)} lines, '
      f'{len(M)} rows, verdict {V["verdict"]}')
